"""
tests/test_provenance_header.py
===============================
The header of every generated file (fragments, their README, FACTS.md) comes
from results/run_manifest.json (scripts/analyze_by_ltrue.py::provenance, used
by scripts/make_paper_tables.py too): it renders the manifest's fields, reads
"in progress" for the wall time inside a run (reproduce_all.py writes the
manifest at the start and sets the total at the end) and says so when there
is no manifest.

The driver side (reproduce_all.py::write_manifest): the final manifest is
the same whether it is written once or at the start, after every step and
at the end.
"""

import json
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)
sys.path.insert(0, _ROOT)

from scripts.analyze_by_ltrue import load_manifest, provenance  # noqa: E402
from reproduce_all import write_manifest  # noqa: E402

MANIFEST = {"mode": "full", "git_head": {"full": "0123456789abcdef", "short": "0123456"},
            "started": "2026-10-01T22:16:39", "finished": "2026-10-02T06:24:15",
            "jobs": 7, "total_seconds": 29256.4}


def _write(results, manifest):
    with open(os.path.join(results, "run_manifest.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh)


def test_header_renders_the_manifest_and_the_fallback(tmp_path):
    results = str(tmp_path)
    assert load_manifest(results) is None
    assert provenance("scripts/x.py", results, code_head="abc1234") == \
        "generated by scripts/x.py from results without a run manifest; generator at code abc1234"

    _write(results, MANIFEST)
    assert load_manifest(results) == MANIFEST
    header = provenance("scripts/x.py", results, code_head="abc1234")
    assert header == ("generated by scripts/x.py from the run started 2026-10-01T22:16:39 on code 0123456 "
                      "(full; 29,256 s; 7 workers)")
    assert "dirty" not in header and "results as of" not in header and "abc1234" not in header


def test_header_inside_a_run_says_in_progress(tmp_path):
    results = str(tmp_path)
    _write(results, dict(MANIFEST, mode="quick", finished=None, total_seconds=None))
    assert provenance("scripts/x.py", results) == \
        "generated by scripts/x.py from the run started 2026-10-01T22:16:39 on code 0123456 (quick; in progress; 7 workers)"


def test_manifest_written_incrementally_equals_the_one_written_once(tmp_path):
    outcomes = [("step one", True, 2.04), ("step two", False, 61.26), ("step three", True, 0.449)]
    started, finished = "2026-10-02T10:00:00", "2026-10-02T10:01:04"
    once, stepwise = str(tmp_path / "once.json"), str(tmp_path / "stepwise.json")

    write_manifest("quick", outcomes, started, 3, finished=finished, path=once)

    write_manifest("quick", [], started, 3, path=stepwise)
    with open(stepwise, encoding="utf-8") as fh:
        start = json.load(fh)
    assert (start["steps"], start["finished"], start["total_seconds"], start["failed_steps"]) == ({}, None, None, [])
    assert start["mode"] == "quick" and start["started"] == started and start["jobs"] == 3
    assert start["git_head"] and start["plan"] and start["versions"]
    for k in range(1, len(outcomes) + 1):
        write_manifest("quick", outcomes[:k], started, 3, path=stepwise)
        with open(stepwise, encoding="utf-8") as fh:
            part = json.load(fh)
        assert list(part["steps"]) == [label for label, _, _ in outcomes[:k]]
        assert part["finished"] is None and part["total_seconds"] is None
    write_manifest("quick", outcomes, started, 3, finished=finished, path=stepwise)

    with open(once, "rb") as a, open(stepwise, "rb") as b:
        assert a.read() == b.read()
    with open(once, encoding="utf-8") as fh:
        final = json.load(fh)
    assert list(final) == ["mode", "git_head", "started", "finished", "jobs", "steps", "failed_steps",
                           "total_seconds", "plan", "versions"]
    assert final["steps"] == {"step one": 2.0, "step two": 61.3, "step three": 0.4}
    assert final["failed_steps"] == ["step two"] and final["total_seconds"] == 63.7 and final["finished"] == finished
