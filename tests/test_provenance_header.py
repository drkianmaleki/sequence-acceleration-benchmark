"""
tests/test_provenance_header.py
===============================
The header of every generated file (fragments, their README, FACTS.md) comes
from results/run_manifest.json (scripts/analyze_by_ltrue.py::provenance, used
by scripts/make_paper_tables.py too): it renders the manifest's fields, says
so when there is no manifest, and refuses a manifest that the excluded-set
artifact shows to be of another run (reproduce_all.py writes the manifest
after its last step, so a generator inside a run finds the previous one).
"""

import json
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)
sys.path.insert(0, _ROOT)

from scripts.analyze_by_ltrue import load_manifest, provenance  # noqa: E402

MANIFEST = {"mode": "full", "git_head": {"full": "0123456789abcdef", "short": "0123456"},
            "started": "2026-10-01T22:16:39", "finished": "2026-10-02T06:24:15",
            "jobs": 7, "total_seconds": 29256.4}


def _write(results, manifest=None, artifact=None):
    if manifest is not None:
        with open(os.path.join(results, "run_manifest.json"), "w", encoding="utf-8") as fh:
            json.dump(manifest, fh)
    if artifact is not None:
        os.makedirs(os.path.join(results, "phase1"), exist_ok=True)
        with open(os.path.join(results, "phase1", "dangerous_methods.json"), "w", encoding="utf-8") as fh:
            json.dump(artifact, fh)


def test_header_renders_the_manifest_and_the_fallback(tmp_path):
    results = str(tmp_path)
    assert load_manifest(results) == (None, "manifest absent")
    assert provenance("scripts/x.py", results, code_head="abc1234") == \
        "generated by scripts/x.py from results without a run manifest (generator at code abc1234)"

    _write(results, MANIFEST, {"created": "2026-10-01T23:11:09", "git_head": "0123456"})
    assert load_manifest(results) == (MANIFEST, None)
    header = provenance("scripts/x.py", results, code_head="abc1234")
    assert header == ("generated by scripts/x.py from the run started 2026-10-01T22:16:39 on code 0123456 "
                      "(full; 29,256 s; 7 workers)")
    assert "dirty" not in header and "results as of" not in header and "abc1234" not in header


def test_header_refuses_the_manifest_of_another_run(tmp_path):
    for artifact, reason in (({"created": "2026-10-03T09:00:00", "git_head": "0123456"}, "outside that run"),
                             ({"created": "2026-10-01T23:11:09", "git_head": "fedcba9"}, "on code fedcba9")):
        results = str(tmp_path / reason.replace(" ", "_"))
        os.makedirs(results)
        _write(results, MANIFEST, artifact)
        M, problem = load_manifest(results)
        assert M == MANIFEST and reason in problem
        header = provenance("scripts/x.py", results, code_head="abc1234")
        assert header.startswith("generated by scripts/x.py from results without a matching run manifest (")
        assert "2026-10-01T22:16:39" in header and reason in header and header.endswith("generator at code abc1234)")
