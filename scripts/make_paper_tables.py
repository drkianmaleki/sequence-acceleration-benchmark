valid = (ev["log_log_slope"].notna() & ev["richardson_r2"].notna()
         & ev["richardson_1"].notna() & ev["rational_fit"].notna())
sub = ev[valid].copy()
f1 = sub["log_log_slope"] > -0.10
f2 = sub["richardson_r2"] < 0.50
losing = sub["rational_fit"] > sub["richardson_1"]
stored = pd.read_csv(f"{RES}/phase2/phase2_rules.csv")
s1 = stored.query("feature=='log_log_slope' and threshold==-0.1 "
                  "and alternative=='rational_fit'").iloc[0]
s2 = stored.query("feature=='richardson_r2' and threshold==0.5 "
                  "and alternative=='rational_fit'").iloc[0]
r1p, r1r = (f1 & losing).sum() / f1.sum(), (f1 & losing).sum() / losing.sum()
r2p, r2r = (f2 & losing).sum() / f2.sum(), (f2 & losing).sum() / losing.sum()
ok = (int(f1.sum()) == int(s1.n_fire) and int(f2.sum()) == int(s2.n_fire)
      and abs(r1p - s1.precision) < 5e-3 and abs(r1r - s1.recall) < 5e-3
      and abs(r2p - s2.precision) < 5e-3 and abs(r2r - s2.recall) < 5e-3)
u = f1 | f2
up = (u & losing).sum() / u.sum()
ur = (u & losing).sum() / losing.sum()
ug = float((sub.loc[u, "rational_fit"] - sub.loc[u, "richardson_1"]).mean())
rep(f"RECOMPUTE (a): replication {'OK' if ok else '** MISMATCH **'} "
    f"(R1 fires {int(f1.sum())} vs {int(s1.n_fire)}, "
    f"R2 fires {int(f2.sum())} vs {int(s2.n_fire)}); "
    f"n={len(sub)}, n_losing={int(losing.sum())}")
rep(f"  COMBINED cascade: fire_rate {u.mean():.3f}, precision {up:.3f}, "
    f"recall {ur:.3f}, mean gain {ug:+.4f}")
rows = [r"Rule & Precision & Recall & Gain & Fire rate \\", r"\midrule",
        (f"Rule~1 ($\\hat{{\\alpha}} > -0.10$) & {r1p:.3f} & {r1r:.3f} & "
         f"${float((sub.loc[f1,'rational_fit']-sub.loc[f1,'richardson_1']).mean()):+.3f}$ & {f1.mean():.3f} \\\\"),
        (f"Rule~2 ($R^2 < 0.50$) & {r2p:.3f} & {r2r:.3f} & "
         f"${float((sub.loc[f2,'rational_fit']-sub.loc[f2,'richardson_1']).mean()):+.3f}$ & {f2.mean():.3f} \\\\"),
        (f"Combined (Rule~1 or Rule~2) & {up:.3f} & {ur:.3f} & ${ug:+.3f}$ & "
         f"{u.mean():.3f} \\\\"),
        r"\meth{richardson\_1} (default) & --- & 0 & 0 & 0 \\"]
frag("t08_cascade_rules.tex",
     "recomputed from phase2_features + phase2_sweep_aggregated", rows, "lrrrr")

