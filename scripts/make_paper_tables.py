def esc(s):
    return s.replace("_", r"\_")


def mth(s):
    return r"\meth{" + esc(s) + "}"


def frag(name, header, rows, colspec):
    """Write a tabular fragment: comment header + booktabs tabular."""
    path = os.path.join(OUT, name)
    with open(path, "w") as f:
        f.write("% AUTO-GENERATED by make_paper_tables.py — do not hand-edit\n")
        f.write(f"% source: {header}\n")
        f.write("\\begin{tabular}{" + colspec + "}\n\\toprule\n")
        for r in rows:
            f.write(r + "\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    print(f"  wrote {name} ({len(rows)} lines)")


